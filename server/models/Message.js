const mongoose = require('mongoose');

const { ObjectId } = mongoose.Schema.Types;

const attachmentSchema = new mongoose.Schema(
  {
    url: { type: String, required: true },
    name: { type: String, required: true },
    mimeType: { type: String, required: true },
    size: { type: Number, required: true },
  },
  { _id: false }
);

const messageSchema = new mongoose.Schema(
  {
    conversation: { type: ObjectId, ref: 'Conversation', required: true },
    sender: { type: ObjectId, ref: 'User', required: true },
    type: { type: String, enum: ['text', 'file', 'system'], default: 'text' },
    text: { type: String, trim: true, maxlength: 5000, default: '' },
    attachment: attachmentSchema,
    // Generated by the client per message. Retries reuse it, so a message that
    // is sent twice (flaky network, reconnect) is only stored once.
    clientId: { type: String, maxlength: 64 },
    // Users (other than the sender) who have read the message.
    readBy: [{ type: ObjectId, ref: 'User' }],
  },
  { timestamps: true }
);

messageSchema.index({ conversation: 1, _id: -1 });
messageSchema.index(
  { sender: 1, clientId: 1 },
  { unique: true, partialFilterExpression: { clientId: { $type: 'string' } } }
);

messageSchema.set('toJSON', {
  transform: (_doc, ret) => {
    delete ret.__v;
    return ret;
  },
});

module.exports = mongoose.model('Message', messageSchema);
